using System.Net;
using System.Text;
using System.Text.RegularExpressions;

namespace RiisSaveEditor.Saves
{
	public sealed record CheatOptions(bool Console = true, bool QuickSave = true, bool Skip = true, bool Rollback = true, bool Menu = true, bool Values = true, bool Strings = true, bool Hud = true, bool Walkthrough = true)
	{
		public bool Any => Console || QuickSave || Skip || Rollback || Menu;
	}

	// Snippets from UnRen. Credit: VepsrP (329951) Updated UnRen, Sam (7899) Original Script, and joelurmel (5474051)
	// another updated variant, from f95zone.
	// Builds one .rpy file with only the chosen enablers. The snippets follow UnRen's console, quick, skip and
	// rollback files; each runs at init 999 so it wins over whatever the game configured earlier.
	public static class RenpyCheats
	{
		public const string FileName = "zz-riis-cheats.rpy";

		public static string Build(CheatOptions options)
		{
			StringBuilder sb = new();
			sb.Append("# Generated by Riis Save Editor. Put this file in the game's \"game\" folder.\n");
			sb.Append("# Delete it to undo everything below.\n");
			sb.Append("# Snippets from UnRen. Credit: VepsrP (329951) Updated UnRen, Sam (7899) Original Script, and joelurmel (5474051) another updated variant, from f95zone.\n\n");
			if (!options.Any)
			{
				return sb.ToString();
			}

			if (options.Menu)
			{
				sb.Append(BuildMenu(options));
			}

			if (!(options.Console || options.QuickSave || options.Skip || options.Rollback))
			{
				return sb.ToString();
			}

			sb.Append("init 999 python:\n");
			if (options.Console)
			{
				sb.Append("""
				          # Console: Shift+O
				          config.developer = True
				          config.console = True

				          """.Indent());
			}

			if (options.QuickSave)
			{
				sb.Append("""
				          # Quick save: F5, quick load: F9
				          try:
				              config.underlay[0].keymap['quickSave'] = QuickSave()
				              config.keymap['quickSave'] = 'K_F5'
				              config.underlay[0].keymap['quickLoad'] = QuickLoad()
				              config.keymap['quickLoad'] = 'K_F9'
				          except:
				              pass

				          """.Indent());
			}

			if (options.Skip)
			{
				sb.Append("""
				          # Skip unseen text, hold Ctrl or press Tab
				          _preferences.skip_unseen = True
				          renpy.game.preferences.skip_unseen = True
				          renpy.config.allow_skipping = True
				          renpy.config.fast_skipping = True
				          try:
				              config.keymap['skip'] = [ 'K_LCTRL', 'K_RCTRL' ]
				          except:
				              pass

				          """.Indent());
			}

			if (options.Rollback)
			{
				sb.Append("""
				          # Rollback: scroll wheel up or Page Up
				          renpy.config.rollback_enabled = True
				          renpy.config.hard_rollback_limit = 256
				          renpy.config.rollback_length = 256
				          def unren_noblock(*args, **kwargs):
				              return
				          renpy.block_rollback = unren_noblock
				          try:
				              config.keymap['rollback'] = [ 'K_PAGEUP', 'repeat_K_PAGEUP', 'K_AC_BACK', 'mousedown_4' ]
				          except:
				              pass

				          """.Indent());
			}

			return sb.ToString();
		}

		private sealed record ModFeature(string Resource, Func<CheatOptions, bool> Enabled, (string Title, string Screen)[] Tabs, string[] Sections);

		// Order here is the tab order. Each feature is one embedded .rpy file under Saves/RenpyMod.
		private static readonly ModFeature[] Features =
		[
			new("values", o => o.Values, [("Values", "rcheats_tab_values"), ("Notify", "rcheats_tab_notify"), ("Log", "rcheats_tab_log")], []),
			new("strings", o => o.Strings, [("Text", "rcheats_tab_strings")], []),
			new("hud", o => o.Hud, [], ["rcheats_sec_hud"]),
			new("walkthrough", o => o.Walkthrough, [], ["rcheats_sec_walk"]),
		];

		private static string ReadResource(string name)
		{
			using Stream stream = typeof(RenpyCheats).Assembly.GetManifestResourceStream($"RenpyMod.{name}.rpy")
			                      ?? throw new InvalidOperationException($"Missing embedded resource {name}.rpy");
			using StreamReader reader = new(stream, Encoding.UTF8);
			return reader.ReadToEnd().Replace("\r\n", "\n");
		}

		// core.rpy carries placeholder comments that receive the tab list, the per-tab screen branches and the General page sections.
		private static string BuildMenu(CheatOptions options)
		{
			List<(string Title, string Screen)> tabs = [("General", "rcheats_tab_general")];
			List<string> sections = [];
			StringBuilder features = new();
			foreach (ModFeature feature in Features.Where(f => f.Enabled(options)))
			{
				tabs.AddRange(feature.Tabs);
				sections.AddRange(feature.Sections);
				features.Append(ReadResource(feature.Resource)).Append('\n');
			}

			StringBuilder core = new();
			foreach (string line in ReadResource("core").Split('\n'))
			{
				string trimmed = line.TrimStart();
				string indent = line[..^trimmed.Length];
				if (trimmed == "# {{TABS}}")
				{
					foreach ((string title, _) in tabs)
					{
						core.Append(indent).Append('"').Append(title).Append("\",\n");
					}
				}
				else if (trimmed == "# {{SECTIONS}}")
				{
					foreach (string section in sections)
					{
						core.Append(indent).Append("use ").Append(section).Append("\n");
					}
				}
				else if (trimmed == "# {{BRANCHES}}")
				{
					for (int i = 0; i < tabs.Count; i++)
					{
						core.Append(indent).Append("if tab == ").Append(i).Append(":\n");
						core.Append(indent).Append("    use ").Append(tabs[i].Screen).Append('\n');
					}
				}
				else
				{
					core.Append(line).Append('\n');
				}
			}

			return core.ToString().TrimEnd('\n') + "\n\n" + features;
		}

		private static readonly Regex Token =new(@"(?<c>#.*)|(?<s>'[^']*'|""[^""]*"")|(?<n>\b\d+\b)|(?<w>\b[A-Za-z_][A-Za-z0-9_]*\b)", RegexOptions.Compiled);
		private static readonly HashSet<string> Keywords = ["init", "python", "try", "except", "def", "return", "pass", "label", "screen", "call", "if", "not", "is", "for", "in", "use", "default", "tag", "modal", "zorder", "key", "add", "vbox", "hbox", "frame", "text", "textbutton", "null"];
		private static readonly HashSet<string> Literals = ["True", "False", "None"];

		// Only ever fed the script built above, so a small tokenizer is enough. Everything is HTML-encoded.
		public static string Highlight(string script)
		{
			StringBuilder sb = new();
			foreach (string line in script.TrimEnd('\n').Split('\n'))
			{
				int pos = 0;
				foreach (Match m in Token.Matches(line))
				{
					sb.Append(WebUtility.HtmlEncode(line[pos..m.Index]));
					string cls = m.Groups["c"].Success ? "tk-comment"
						: m.Groups["s"].Success ? "tk-string"
						: m.Groups["n"].Success ? "tk-number"
						: Keywords.Contains(m.Value) ? "tk-keyword"
						: Literals.Contains(m.Value) ? "tk-literal"
						: line[(m.Index + m.Length)..].StartsWith('(') || line[..m.Index].EndsWith("def ") ? "tk-function"
						: "";
					string text = WebUtility.HtmlEncode(m.Value);
					sb.Append(cls.Length == 0 ? text : $"<span class=\"{cls}\">{text}</span>");
					pos = m.Index + m.Length;
				}

				sb.Append(WebUtility.HtmlEncode(line[pos..])).Append('\n');
			}

			return sb.ToString();
		}

		private static string Indent(this string block) =>
			string.Concat(block.Split('\n').Select(l => l.Length == 0 ? "\n" : "    " + l + "\n"));
	}
}
